        \\
    , doc);
}

test "quotes yaml scalars that plain style would misread" {
    const doc = try render(std.testing.allocator, .{
        .title = "note: draft",
        .resource = "recordings/r.wav",
        .timestamp = "2026-08-26T12:00:00Z",
        .model = "nova-3",
        .language = "pt-BR",
        .duration_sec = null,
    }, &.{});
    defer std.testing.allocator.free(doc);

    try std.testing.expect(std.mem.indexOf(u8, doc, "title: \"note: draft\"\n") != null);
    try std.testing.expect(std.mem.indexOf(u8, doc, "resource: recordings/r.wav\n") != null);
}
